export function getHobbyMilestone(xp) {
  const n = Number(xp || 0);
  if (n >= 15) return "Low‑key Legendary";
  if (n >= 10) return "Skilled";
  if (n >= 6) return "Committed";
  if (n >= 3) return "Regular";
  if (n >= 1) return "Curious Beginner";
  return "Not Started";
}

function hashToIndex(str, mod) {
  let h = 0;
  for (let i = 0; i < str.length; i++) {
    h = ((h << 5) - h) + str.charCodeAt(i);
    h |= 0;
  }
  return Math.abs(h) % mod;
}

export function seededPickLine(runSeed, hobbyId, age, xp, lines) {
  const arr = Array.isArray(lines) ? lines : [];
  if (arr.length === 0) return "";
  const idx = hashToIndex(`${runSeed}|hobby|${hobbyId}|${age}|${xp}`, arr.length);
  return arr[idx];
}

