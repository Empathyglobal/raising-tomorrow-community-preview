// Helper to get a random message for a culture, ensuring no immediate repeat
export function getCultureMessage(cultureId, lastMsgId, rng = Math.random) {
  const pool = CULTURE_MSG_POOLS[cultureId] || [];
  if (pool.length === 0) return "You share a story from your roots. (Content coming soon)";
  
  // Anti-repeat logic could go here, but prompt asked for verbatim content mostly.
  // For now simple random is fine, or simple filter.
  const available = pool.filter(m => m !== lastMsgId);
  const list = available.length > 0 ? available : pool;
  
  return list[Math.floor(rng() * list.length)];
}

// Helper to get fusion message
export function getFusionMessage(rng = Math.random) {
  if (!FUSION_MSG_POOL || FUSION_MSG_POOL.length === 0) return "You blend two traditions beautifully.";
  return FUSION_MSG_POOL[Math.floor(rng() * FUSION_MSG_POOL.length)];
}

