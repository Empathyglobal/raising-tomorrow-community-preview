// COACH NOTE SELECTION ENGINE
export function getCoachNote(context, state, rng = Math.random) {
  const { type, age, choiceLetter, actionId, deltas, snapshot } = context;
  const { INT, EMP, DIS, CON, LOVE, STRESS } = snapshot;
  
  // Build tag pool based on context
  let priorityTags = [];
  let secondaryTags = [];
  
  // 1) Handle E (harm) choice
  if (choiceLetter === "E") {
    priorityTags.push("harm");
  }
  
  // 2) Handle love decrease
  if (deltas?.loveDelta < 0 || LOVE <= 3) {
    priorityTags.push("repair", "connection");
  }
  
  // 3) Handle high stress
  if (STRESS >= 8) {
    priorityTags.push("parent-stress", "regulation");
  }
  
  // 4) Handle discipline extremes
  if (DIS >= 10) {
    priorityTags.push("flexibility", "warmth");
    secondaryTags.push("discipline");
  } else if (DIS <= 1) {
    priorityTags.push("structure", "limits");
    secondaryTags.push("discipline");
  }
  
  // 5) Handle empathy/connection needs
  if (EMP <= 3 || (deltas?.empathy && deltas.empathy > 0)) {
    secondaryTags.push("feelings", "empathy");
  }
  
  // 6) Handle confidence issues
  if (CON <= 3) {
    secondaryTags.push("autonomy", "confidence");
  }
  
  // 7) Handle boundaries/structure themes
  if (deltas?.discipline && deltas.discipline > 0) {
    secondaryTags.push("boundaries", "structure");
  }
  
  // 8) Fallback tags
  if (priorityTags.length === 0 && secondaryTags.length === 0) {
    secondaryTags.push("connection", "guidance");
  }
  
  // Filter notes by priority tags first
  let candidates = COACH_NOTES.filter(note => 
    priorityTags.some(tag => note.tags.includes(tag))
  );
  
  // If no priority matches, use secondary tags
  if (candidates.length === 0) {
    candidates = COACH_NOTES.filter(note => 
      secondaryTags.some(tag => note.tags.includes(tag))
    );
  }
  
  // If still no matches, use all connection notes as fallback
  if (candidates.length === 0) {
    candidates = COACH_NOTES.filter(note => note.tags.includes("connection"));
  }
  
  // Pick random from candidates
  const chosen = candidates[Math.floor(rng() * candidates.length)];
  
  return {
    body: chosen.body,
    tryNext: chosen.tryNext || null
  };
}