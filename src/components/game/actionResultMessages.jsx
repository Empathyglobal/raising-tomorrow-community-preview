// Helper to pick a random body from the library with optional seeding
export function getActionResultCopy(actionId, age, seed = Date.now()) {
  const library = ACTION_RESULT_MESSAGES[actionId];
  if (!library) {
    return {
      title: "Action Complete",
      body: "Done."
    };
  }
  
  // Simple seeded random selection
  const index = (age + seed) % library.bodies.length;
  return {
    title: library.title,
    body: library.bodies[index]
  };
}

// Feedback for stat growth observations (with content packs variety support)
export function pickFeedback(stat, usedRecently = []) {
  const pools = {
    intelligence: [
      "They're picking things up faster.",
      "You see them connecting dots.",
      "The learning is visible.",
      "Their questions get sharper.",
      "You notice them problem-solving.",
      "Curiosity is blooming.",
      "They remember things you forgot you taught."
    ],
    empathy: [
      "They're noticing feelings more.",
      "You catch them being kind unprompted.",
      "Connection deepens.",
      "They ask how you're doing.",
      "Compassion shows up naturally.",
      "They defend the underdog.",
      "Warmth radiates."
    ],
    discipline: [
      "Structure is taking root.",
      "They follow through more often.",
      "Habits are forming.",
      "They don't need reminders as much.",
      "Routines feel smoother.",
      "Consistency compounds.",
      "They finish what they start."
    ],
    confidence: [
      "They're trying new things.",
      "You see less hesitation.",
      "Bravery is growing.",
      "They speak up more.",
      "Fear doesn't freeze them.",
      "Bold moves increase.",
      "They own their choices."
    ]
  };

  let pool = pools[stat] || ["Something shifts.", "You notice growth.", "Progress lands."];
  
  // Content packs: avoid recently used lines
  if (usedRecently.length > 0) {
    const unseenPool = pool.filter(line => !usedRecently.includes(line));
    if (unseenPool.length > 0) {
      pool = unseenPool;
    }
  }

  return pool[Math.floor(Math.random() * pool.length)];
}