// Helper to get a random callback for a pattern
export function getPatternCallback(patternId, seed = Date.now()) {
  const callbacks = PATTERN_CALLBACKS[patternId];
  if (!callbacks || callbacks.length === 0) return null;
  
  const rng = mulberry32(hashString(seed + patternId));
  const index = Math.floor(rng() * callbacks.length);
  return callbacks[index];
}

// Helper to get random epilogue echo
export function getEpilogueEcho(seed = Date.now()) {
  const rng = mulberry32(hashString(seed));
  const index = Math.floor(rng() * EPILOGUE_ECHOES.length);
  return EPILOGUE_ECHOES[index];
}

// Helper to get reflective moment by type
export function getReflectiveMoment(type) {
  return REFLECTIVE_MOMENTS[type] || REFLECTIVE_MOMENTS.transition;
}

// Seeded RNG helpers
function hashString(str) {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    const char = str.charCodeAt(i);
    hash = ((hash << 5) - hash) + char;
    hash = hash & hash;
  }
  return Math.abs(hash);
}

function mulberry32(seed) {
  return function() {
    seed |= 0;
    seed = seed + 0x6D2B79F5 | 0;
    let t = Math.imul(seed ^ seed >>> 15, 1 | seed);
    t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
    return ((t ^ t >>> 14) >>> 0) / 4294967296;
  };
}