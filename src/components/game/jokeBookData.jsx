// Pick a joke that's different from the last shown
export function pickJoke(lastIndex, avoidIndex = -1) {
  if (JOKE_BOOK_JOKES.length === 0) return { index: 0, joke: "Why did the parent read jokes? To build confidence!" };
  
  let index;
  if (JOKE_BOOK_JOKES.length === 1) {
    index = 0;
  } else {
    do {
      index = Math.floor(Math.random() * JOKE_BOOK_JOKES.length);
    } while (index === lastIndex || index === avoidIndex);
  }
  
  return { index, joke: JOKE_BOOK_JOKES[index] };
}