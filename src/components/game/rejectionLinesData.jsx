export const pickRandom = (arr) => arr[Math.floor(Math.random() * arr.length)];

export const formatLine = (line, vars = {}) => {
  const name = (vars.name && String(vars.name).trim()) ? String(vars.name).trim() : 'They';
  return line.replaceAll('{name}', name);
};

export const getFunnyRejectionLine = ({ mode, type, name }) => {
  // mode: 'celebrity' | 'regular'
  // type: 'no_match' | 'ghost'
  let pool = [];

  if (mode === 'celebrity' && type === 'no_match') pool = CELEB_NO_MATCH_LINES;
  if (mode === 'celebrity' && type === 'ghost') pool = CELEB_GHOST_LINES;
  if (mode === 'regular' && type === 'no_match') pool = REGULAR_NO_MATCH_LINES;
  if (mode === 'regular' && type === 'ghost') pool = REGULAR_GHOST_LINES;

  if (!pool || pool.length === 0) {
    return formatLine('No match. {name} did not respond.', { name });
  }
  return formatLine(pickRandom(pool), { name });
};

