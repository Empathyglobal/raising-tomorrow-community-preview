function weightedPick(items, weights) {
  const total = weights.reduce((a, b) => a + b, 0);
  let r = Math.random() * total;
  for (let i = 0; i < items.length; i++) {
    r -= weights[i];
    if (r <= 0) return items[i];
  }
  return items[0];
}

export function generateProceduralCeleb() {
  const age = 19 + Math.floor(Math.random() * 27); // 19-45
  const category = weightedPick(CATEGORIES, CATEGORY_WEIGHTS);
  
  // Fame tier
  const r = Math.random();
  let fameTier = "C";
  if (r < 0.05) fameTier = "A";
  else if (r < 0.40) fameTier = "B";

  // Name
  const nameType = Math.random();
  let name = "";
  const first = GEN_FIRST_NAMES[Math.floor(Math.random() * GEN_FIRST_NAMES.length)];
  
  if (nameType < 0.4) {
    // First + Last
    const last = GEN_LAST_NAMES[Math.floor(Math.random() * GEN_LAST_NAMES.length)];
    name = `${first} ${last}`;
  } else if (nameType < 0.7) {
    // First + Stage
    const last = GEN_STAGE_LAST[Math.floor(Math.random() * GEN_STAGE_LAST.length)];
    name = `${first} ${last}`;
  } else {
    // Two word stage name (using stage last + random noun-ish or just two stage lasts?)
    // Let's stick to prompt options. "Two-word stage name".
    const part1 = GEN_STAGE_LAST[Math.floor(Math.random() * GEN_STAGE_LAST.length)];
    const part2 = GEN_STAGE_LAST[Math.floor(Math.random() * GEN_STAGE_LAST.length)];
    name = `${part1} ${part2}`;
  }

  // Bio
  const bioSuffix = BIO_LINES_GENERIC[Math.floor(Math.random() * BIO_LINES_GENERIC.length)];
  const bioLine = `${CATEGORY_TITLES[category] || "Famous."} | ${bioSuffix}`;

  // Stats
  let standards, privacy, drama;
  if (fameTier === "A") {
    standards = 0.70 + Math.random() * 0.25;
    privacy = 0.55 + Math.random() * 0.40;
  } else if (fameTier === "B") {
    standards = 0.45 + Math.random() * 0.35;
    privacy = 0.35 + Math.random() * 0.45;
  } else {
    standards = 0.25 + Math.random() * 0.40;
    privacy = 0.15 + Math.random() * 0.50;
  }
  drama = 0.10 + Math.random() * 0.80;

  return {
    id: `celeb_gen_${Date.now()}_${Math.random()}`,
    name,
    isCuratedFictional: false,
    category,
    fameTier,
    age,
    bioLine,
    stats: {
      standardsNormalized: standards,
      privacyNormalized: privacy,
      dramaNormalized: drama
    },
    // Visuals (simple emoji based on name hash/random)
    avatar: "🌟"
  };
}

export function generateRoster(count = 8) {
  const roster = [];
  const curatedCount = Math.floor(count * 0.6); // 60% curated
  const proceduralCount = count - curatedCount;

  // Shuffle curated list
  const shuffledCurated = [...CURATED_CELEBS].sort(() => 0.5 - Math.random());
  
  // Pick curated
  const pickedCurated = shuffledCurated.slice(0, curatedCount).map((c, i) => {
    // Assign stats for curated
    let standards, privacy, drama;
    if (c.fameTier === "A") {
      standards = 0.70 + Math.random() * 0.25;
      privacy = 0.55 + Math.random() * 0.40;
      drama = 0.20 + Math.random() * 0.60;
    } else {
      standards = 0.45 + Math.random() * 0.35;
      privacy = 0.35 + Math.random() * 0.45;
      drama = 0.20 + Math.random() * 0.65;
    }

    const bio = BIO_LINES_CURATED[Math.floor(Math.random() * BIO_LINES_CURATED.length)];

    return {
      ...c,
      id: `celeb_curated_${c.name.replace(/\s/g, '')}_${Date.now()}`,
      isCuratedFictional: true,
      age: 25 + Math.floor(Math.random() * 20), // rough age sim
      bioLine: bio,
      stats: {
        standardsNormalized: standards,
        privacyNormalized: privacy,
        dramaNormalized: drama
      },
      avatar: "⭐"
    };
  });

  roster.push(...pickedCurated);

  // Fill procedural
  for (let i = 0; i < proceduralCount; i++) {
    roster.push(generateProceduralCeleb());
  }

  // Shuffle final roster
  return roster.sort(() => 0.5 - Math.random());
}

